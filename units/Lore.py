# Что говорит отголосок, когда главы нет (сюжет пройден)
ECHO_SILENT = ("Отголосок", ["Тихо. [...] больше нечего сказать."])


def echo_for_act(act_id):
    """Реплика отголоска для текущей главы."""
    return ECHOES.get(act_id, ECHO_SILENT)


def inscription_by_variant(variant):
    """id надписи по номеру варианта (кадру тайла). Неизвестный номер даёт
    стёртую плиту, а не падение."""
    if isinstance(variant, int) and 0 <= variant < len(TABLET_VARIANTS):
        return TABLET_VARIANTS[variant]
    return ""


def get_inscription(inscription_id):
    """(заголовок, строки). Для неизвестного id — заглушка, а не падение:
    мир мог быть создан версией с другими надписями."""
    return INSCRIPTIONS.get(
        inscription_id,
        ("Стёртая плита", ["Знаки не читаются.", "[...]"]),
    )


def all_ids():
    return tuple(INSCRIPTIONS)
