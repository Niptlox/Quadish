"""Сборка структур из ASCII-схемы.

Структуры в units/Map/Structures.py заданы «сырыми» списками ячеек вида
`[[31, 75, 0, 0], [31, 75, 0, 0], ...]` — на 5 построек ушло 75 КБ, такое
невозможно ни читать, ни править. Здесь структура пишется картинкой:

    build_ascii([
        "..###..",
        "..#C#..",
        "..###..",
    ])

Один символ — один тайл (см. LEGEND). Прочность подставляется сама из
TILES_SOLIDITY, поэтому её нельзя случайно разойтись с ванильной.

Формат на выходе — тот же, что у старых структур: ((ширина, высота),
[[тип, прочность, кадр, состояние], ...]) плюс, если заданы задние
панельки, третий элемент — их список.
"""
from units.Tiles import TILES_SOLIDITY

# Символ -> id тайла. '.' — структурная пустота (150): рельеф на этом
# месте не трогается, что позволяет вписывать постройку в склон.
# ' ' — воздух (0): наоборот, расчищает место под комнату.
LEGEND = {
    '.': 150,  # не трогать рельеф
    ' ': 0,    # воздух (расчистить)
    'g': 1,    # дёрн
    'd': 2,    # земля
    's': 3,    # камень
    'B': 4,    # блор
    'G': 5,    # гранит
    'p': 11,   # доски
    'w': 12,   # древесина
    'T': 110,  # живое дерево (ствол)
    'l': 105,  # листва
    'v': 106,  # лианы
    '#': 31,   # каменный кирпич
    'm': 32,   # замшелый каменный кирпич
    'o': 33,   # старый каменный кирпич
    'b': 21,   # блок блоровой руды
    'c': 22,   # блок медной руды
    'A': 23,   # блок золотой руды
    'i': 24,   # блок железной руды
    'S': 25,   # блок серебряной руды
    '~': 120,  # вода
    't': 121,  # стол
    'h': 122,  # стул
    'D': 123,  # дверь
    'K': 125,  # котёл
    'W': 126,  # шкаф
    'H': 127,  # люк
    'C': 129,  # сундук
    'F': 131,  # печка
    'z': 130,  # спальный мешок
    'x': 9,    # динамит
    '*': 215,  # лампа
    '-': 213,  # провод
    '/': 214,  # рычаг
    '!': 212,  # нажимная плита
    'q': 101,  # куст
    ',': 104,  # трава
    'Y': 103,  # кактус
    # Плиты с надписями: цифра — номер варианта надписи (кадр тайла),
    # см. Lore.TABLET_VARIANTS. Значение вида (тайл, кадр).
    '0': (300, 0),  # алтарь
    '1': (300, 1),  # дозорный пост
    '2': (300, 2),  # затопленный храм
    '3': (300, 3),  # обсерватория
    '4': (300, 4),  # забой
    '5': (300, 5),  # оранжерея
    '6': (300, 6),  # бункер, последняя запись
    '7': (300, 7),  # подземный знак
    '8': (300, 8),  # путевой камень
    '9': (300, 9),  # стоянка в тундре
}

BACKTILE_LEGEND = {
    '.': 0,
    's': 1003,  # панелька камня
}

# Фундамент: блок ставится как обычно, а от него постройка сама
# достраивается ВНИЗ до земли (GameMap.set_structure). Нужно потому, что
# рельеф неровный: структура, посаженная на поверхность, иначе висела бы
# над склоном одним углом. Ставится в нижнюю строку схемы.
FOUNDATION_LEGEND = {
    '=': 31,   # кирпичный фундамент (постройки)
    '_': 3,    # каменный фундамент (естественные/грубые постройки)
}


class StructureError(Exception):
    """Схема структуры описана неверно."""


def build_ascii(rows, back=None, legend=None):
    """Собрать структуру из списка строк одинаковой длины.

    back — необязательная схема задних панелек той же формы.
    """
    legend = {**LEGEND, **(legend or {})}
    if not rows:
        raise StructureError("схема структуры пустая")
    width = len(rows[0])
    if width == 0:
        raise StructureError("в схеме структуры нулевая ширина")
    for y, row in enumerate(rows):
        if len(row) != width:
            raise StructureError(
                f"строка {y + 1} длиной {len(row)}, а первая — {width}: "
                "все строки схемы должны быть одной длины")

    array = []
    foundation = []
    for dy, row in enumerate(rows):
        for dx, ch in enumerate(row):
            if ch not in legend and ch not in FOUNDATION_LEGEND:
                raise StructureError(f"неизвестный символ схемы {ch!r}")
            if ch in FOUNDATION_LEGEND:
                # столб фундамента: сам блок ставится как обычно, а вниз от
                # него постройка достраивается до земли уже при установке
                t, state_img = FOUNDATION_LEGEND[ch], 0
                foundation.append((dx, dy, t))
            else:
                value = legend[ch]
                # значение легенды — либо id тайла, либо (id, кадр): кадр несёт
                # вариант тайла (например, какую надпись показывает плита)
                t, state_img = value if isinstance(value, tuple) else (value, 0)
            array.append([t, TILES_SOLIDITY.get(t, -1), state_img, 0])

    size = (width, len(rows))
    if back is None:
        # 2 элемента, если фундамента нет — старый формат не меняется
        return (size, array, [], foundation) if foundation else (size, array)

    if len(back) != len(rows) or any(len(r) != width for r in back):
        raise StructureError("схема задних панелек должна совпадать по размеру с основной")
    backtiles = []
    for row in back:
        for ch in row:
            if ch not in BACKTILE_LEGEND:
                raise StructureError(f"неизвестный символ задней панельки {ch!r}")
            backtiles.append(BACKTILE_LEGEND[ch])
    if foundation:
        return size, array, backtiles, foundation
    return size, array, backtiles
