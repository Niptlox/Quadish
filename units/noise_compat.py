        if base:
            x += base * 97.13
            y += base * 57.71
        if octaves == 1:
            return _snoise2_raw(x, y)
        total = 0.0
        freq = 1.0
        amp = 1.0
        max_amp = 0.0
        for _ in range(octaves):
            total += _snoise2_raw(x * freq, y * freq) * amp
            max_amp += amp
            freq *= lacunarity
            amp *= persistence
        return total / max_amp
