    _F2 = 0.5 * (math.sqrt(3.0) - 1.0)
    _G2 = (3.0 - math.sqrt(3.0)) / 6.0

    def _snoise2_raw(x, y):
        s = (x + y) * _F2
        i = math.floor(x + s)
        j = math.floor(y + s)
        t = (i + j) * _G2
        x0 = x - (i - t)
        y0 = y - (j - t)
        if x0 > y0:
            i1, j1 = 1, 0
        else:
            i1, j1 = 0, 1
        x1 = x0 - i1 + _G2
        y1 = y0 - j1 + _G2
        x2 = x0 - 1.0 + 2.0 * _G2
        y2 = y0 - 1.0 + 2.0 * _G2
        ii = int(i) & 255
        jj = int(j) & 255
        n = 0.0

