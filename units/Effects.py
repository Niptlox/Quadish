"""Длящиеся эффекты: то, что действует какое-то время, а не мгновенно.

Зачем это отдельная система. Все «зелья» в Quadish были мгновенными и
необратимыми: зелье жизни поднимало максимум здоровья на 20 навсегда, зелье
прыжка навсегда добавляло прыжок. У такой награды нет ни момента применения,
ни решения «когда пить»: выпил, забыл, эффект растворился в статистике. Это же
делало зельеварение бессмысленным как занятие — варить второй раз незачем.

Эффект с длительностью возвращает решение: у него есть момент («сейчас пью,
потому что сейчас дерусь»), цена (сварить) и окно, в которое надо успеть. И его
видно на экране, то есть игрок понимает, что с ним происходит.

Устройство. Одно правило, из которого следует всё остальное: **эффект ничего не
меняет в объекте**. Он не трогает `max_speed`, не прибавляет к `punch_damage` —
он только лежит в списке, а места, которым это важно, спрашивают множитель
(`mult`) или наличие (`has`). Причина простая и проверенная на этом проекте:
любая правка поля пережила бы сам эффект. Скорость, поднятая на 40% и не
опущенная обратно (игрок вышел в меню, мир сохранился, зелье кончилось где-то
в другом кадре), осталась бы навсегда — и отладить это потом невозможно, потому
что в сейве лежит просто «max_speed = 0.46».

Хранение: {вид: [тактов осталось, сила]}. Это обычные числа, поэтому эффекты
переживают сохранение мира вместе с игроком и не требуют своей ветки в
сериализации.
"""
from units.common import FPS

# Виды эффектов. Ключи — строки, а не числа: они попадают в сейв, и строку в
# нём можно прочитать глазами через год.
SPEED = "speed"             # быстрее бег
STRENGTH = "strength"       # больнее удар
STONESKIN = "stoneskin"     # меньше получаемый урон
REGEN = "regen"             # лечит понемногу
FIREPROOF = "fireproof"     # не жжёт лава и другие опасные блоки
BREATH = "breath"           # быстрее плавание

# Описание для экрана и для баланса. mult — множитель по умолчанию (силу можно
# задать сильнее при выдаче), tint — цвет полоски в HUD.
EFFECTS = {
    SPEED:     {"title": "Скорость",     "mult": 1.45, "tint": "#38BDF8"},
    STRENGTH:  {"title": "Сила",         "mult": 1.6,  "tint": "#F97316"},
    STONESKIN: {"title": "Камень",       "mult": 0.5,  "tint": "#A8A29E"},
    REGEN:     {"title": "Заживление",   "mult": 1.0,  "tint": "#4ADE80"},
    FIREPROOF: {"title": "Несгораемость", "mult": 1.0, "tint": "#FB7185"},
    BREATH:    {"title": "Дыхание",      "mult": 1.6,  "tint": "#22D3EE"},
}

# Как часто лечит заживление. Раз в секунду, а не каждый кадр: лечение по
# единице на кадр — это 60 здоровья в секунду, то есть бессмертие.
REGEN_PERIOD = FPS
REGEN_HEAL = 1


class Effects:
    """Набор действующих эффектов одного существа (пока только игрока).

    Сам объект в сохранение НЕ идёт, а состояние — идёт: словарь лежит полем
    владельца (`owner.effects_state`), и это не педантизм. Effects держит
    ссылку на владельца, владелец — на игру, а в игре есть pygame.time.Clock,
    который не пиклится: сохранение мира падало ровно на этом. Числа в поле
    игрока сериализуются сами, вместе с остальными его полями.
    """

    def __init__(self, owner):
        self.owner = owner
        if not isinstance(getattr(owner, "effects_state", None), dict):
            owner.effects_state = {}

    @property
    def active(self):
        """Состояние эффектов: {вид: [тактов осталось, сила]}.

        Через свойство, а не через ссылку на словарь: загрузка мира
        ПЕРЕПРИСВАИВАЕТ поле игрока, и сохранённая ссылка смотрела бы в старый
        словарь — эффекты после загрузки жили бы отдельно от игрока.
        """
        state = getattr(self.owner, "effects_state", None)
        if not isinstance(state, dict):
            state = {}
            self.owner.effects_state = state
        return state

    # ---------- выдача ----------

    def add(self, kind, tacts, power=None):
        """Наложить эффект. Повторная выдача ПРОДЛЕВАЕТ, а не складывает силу.

        Складывать силу нельзя: два зелья скорости давали бы 1.45 * 1.45, три —
        уже полёт. Продление же честно отвечает на «выпил второе» и не создаёт
        способа сломать баланс запасами.
        """
        if kind not in EFFECTS:
            return False
        if power is None:
            power = EFFECTS[kind]["mult"]
        cur = self.active.get(kind)
        if cur is None:
            self.active[kind] = [tacts, power]
        else:
            cur[0] += tacts
            # Сила берётся максимальная из двух: слабое зелье не должно
            # ослаблять уже действующее сильное.
            cur[1] = max(cur[1], power) if power >= 1 else min(cur[1], power)
        return True

    def clear(self):
        self.active.clear()

    # ---------- запросы ----------

    def has(self, kind):
        return kind in self.active

    def mult(self, kind, default=1.0):
        """Множитель эффекта или default, если эффекта нет."""
        cur = self.active.get(kind)
        return default if cur is None else cur[1]

    def left(self, kind):
        """Сколько тактов осталось (0 — эффекта нет)."""
        cur = self.active.get(kind)
        return 0 if cur is None else max(0, int(cur[0]))

    def visible(self):
        """Что показать на экране: [(вид, тактов, сила)], по убыванию времени."""
        return sorted(((k, int(v[0]), v[1]) for k, v in self.active.items()),
                      key=lambda it: -it[1])

    # ---------- такт ----------

    def update(self, tact):
        """Отсчитать время и применить то, что действует само (заживление)."""
        if not self.active:
            return
        for kind in list(self.active):
            state = self.active[kind]
            state[0] -= 1
            if state[0] <= 0:
                del self.active[kind]
        if REGEN in self.active and tact % REGEN_PERIOD == 0:
            owner = self.owner
            heal = int(REGEN_HEAL * self.active[REGEN][1])
            if owner.lives < owner.max_lives:
                owner.lives = min(owner.max_lives, owner.lives + heal)


# Что даёт съеденный предмет: индекс -> [(вид, длительность в тактах, сила)].
# Таблица здесь, а не у предмета, по той же причине, по которой лут лежит в
# units/Loot.py: это баланс, и его надо видеть целиком в одном месте.
ITEM_EFFECTS = {
    # Таблетка (4 ягоды + слизь) — самое раннее лекарство в игре. Лечит не
    # сразу, а десять секунд: это делает её решением «выпить ЗАРАНЕЕ», а не
    # кнопкой отмены полученного урона.
    412: [(REGEN, FPS * 10, 1)],
    413: [(SPEED, FPS * 45)],
    414: [(STRENGTH, FPS * 30)],
    415: [(STONESKIN, FPS * 30)],
    416: [(FIREPROOF, FPS * 25)],
    417: [(BREATH, FPS * 60)],
}
